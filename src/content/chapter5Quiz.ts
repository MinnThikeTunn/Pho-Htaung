export interface QuizOption {
  label: 'က' | 'ခ' | 'ဂ' | 'ဃ';
  text: string;
}

export interface QuizQuestion {
  id: number;
  tier: 1 | 2 | 3 | 4;
  tierName: string;
  category: 'စကားထာ' | 'စကားပုံ' | 'ပုဂံသမိုင်း' | 'မြန်မာ့ယဉ်ကျေးမှု' | 'စာပေနှင့် အနုပညာ';
  question: string;
  options: QuizOption[];
  correctIndex: number; // 0=က, 1=ခ, 2=ဂ, 3=ဃ
  honestClue: string;   // Truthful clue from U Gyi pointing toward correct answer
  deceptiveClue: string;// Deceptive trick clue from U Gyi pointing toward a distractor
  ugyiTrick: string;    // Backward compatibility default
  explanation: string;
  activeClue?: string;
  isClueHonest?: boolean;
}

export interface ActiveQuizQuestion extends QuizQuestion {
  activeClue: string;
  isClueHonest: boolean;
}

// Helper to wrap question with default aliases
function makeQuestion(
  id: number,
  tier: 1 | 2 | 3 | 4,
  tierName: string,
  category: 'စကားထာ' | 'စကားပုံ' | 'ပုဂံသမိုင်း' | 'မြန်မာ့ယဉ်ကျေးမှု' | 'စာပေနှင့် အနုပညာ',
  question: string,
  options: [string, string, string, string],
  correctIndex: number,
  honestClue: string,
  deceptiveClue: string,
  explanation: string
): QuizQuestion {
  return {
    id,
    tier,
    tierName,
    category,
    question,
    options: [
      { label: 'က', text: options[0] },
      { label: 'ခ', text: options[1] },
      { label: 'ဂ', text: options[2] },
      { label: 'ဃ', text: options[3] },
    ],
    correctIndex,
    honestClue,
    deceptiveClue,
    ugyiTrick: deceptiveClue,
    explanation,
  };
}


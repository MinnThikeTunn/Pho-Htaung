/**
 * Randomize option placement for a question (0=က, 1=ခ, 2=ဂ, 3=ဃ).
 * Permutes options so the correct answer (and distractor) are placed into any slot uniformly,
 * and dynamically updates U Gyi's honest and deceptive clues to reference the new letter slots.
 */
export function randomizeQuestionPlacement(q: QuizQuestion): QuizQuestion {
  const letters: Array<'က' | 'ခ' | 'ဂ' | 'ဃ'> = ['က', 'ခ', 'ဂ', 'ဃ'];
  const indices = [0, 1, 2, 3];
  for (let i = 3; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = indices[i]!;
    indices[i] = indices[j]!;
    indices[j] = tmp;
  }

  const newOptions: QuizOption[] = indices.map((origIdx, newPos) => ({
    label: letters[newPos]!,
    text: q.options[origIdx]!.text,
  }));

  const newCorrectIndex = indices.indexOf(q.correctIndex);
  const origCorrectLetter = letters[q.correctIndex]!;
  const newCorrectLetter = letters[newCorrectIndex]!;

  const deceptMatch = q.deceptiveClue.match(/\(([ကခဂဃ])\)/);
  const origDeceptiveLetter = deceptMatch ? deceptMatch[1] : null;
  const origDeceptiveIndex = origDeceptiveLetter ? letters.indexOf(origDeceptiveLetter as any) : -1;
  const newDeceptiveIndex = origDeceptiveIndex >= 0 ? indices.indexOf(origDeceptiveIndex) : -1;
  const newDeceptiveLetter = newDeceptiveIndex >= 0 ? letters[newDeceptiveIndex] : null;

  const honestClue = q.honestClue.replace(`(${origCorrectLetter})`, `(${newCorrectLetter})`);

  let deceptiveClue = q.deceptiveClue;
  if (origDeceptiveLetter && newDeceptiveLetter) {
    deceptiveClue = deceptiveClue.replace(`(${origDeceptiveLetter})`, `(${newDeceptiveLetter})`);
    deceptiveClue = deceptiveClue.replace(
      new RegExp(`(?<=[\\s.,!?])${origDeceptiveLetter}(?=[\\s.,!?]|ကို|ပဲ|သာ)`, 'g'),
      newDeceptiveLetter
    );
  }

  return {
    ...q,
    options: newOptions,
    correctIndex: newCorrectIndex,
    honestClue,
    deceptiveClue,
    ugyiTrick: deceptiveClue,
  };
}

/**
 * Randomly select between honest clue and deceptive trick clue (50/50 balance)
 */
export function assignActiveClue(q: QuizQuestion): ActiveQuizQuestion {
  const isHonest = Math.random() < 0.5;
  return {
    ...q,
    activeClue: isHonest ? q.honestClue : q.deceptiveClue,
    isClueHonest: isHonest,
  };
}

/**
 * Shuffle an array without mutating
 */
function shuffleArray<T>(items: readonly T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = copy[i]!;
    copy[i] = copy[j]!;
    copy[j] = temp;
  }
  return copy;
}

/**
 * Sample N items from pool, prioritizing questions that are NOT in usedIds.
 */
function sampleTierQuestions(
  pool: readonly QuizQuestion[],
  count: number,
  usedIds: Set<number>
): ActiveQuizQuestion[] {
  // Separate into unused and used
  const unused = pool.filter(q => !usedIds.has(q.id));
  const shuffledUnused = shuffleArray(unused);

  let selected: QuizQuestion[] = [];
  if (shuffledUnused.length >= count) {
    selected = shuffledUnused.slice(0, count);
  } else {
    // If we ran out of unused questions in this tier, take all unused and fill rest from shuffled used
    selected = [...shuffledUnused];
    const needed = count - selected.length;
    const usedPool = pool.filter(q => usedIds.has(q.id));
    const shuffledUsed = shuffleArray(usedPool);
    selected.push(...shuffledUsed.slice(0, needed));
  }

  // Mark selected as used in the set
  selected.forEach(q => usedIds.add(q.id));

  // Randomize option placement (ka, kha, ga, gha) and assign 50/50 honest vs. deceptive clue
  return selected.map(q => assignActiveClue(randomizeQuestionPlacement(q)));
}

/**
 * Generate a complete 20-question run:
 * 5 questions from Tier 1 (Easy: Q1-Q5)
 * 5 questions from Tier 2 (Intermediate: Q6-Q10)
 * 5 questions from Tier 3 (Advanced: Q11-Q15)
 * 5 questions from Tier 4 (Expert: Q16-Q20)
 */
export function generateQuizRun(historySet: Set<number> = new Set()): ActiveQuizQuestion[] {
  const t1 = sampleTierQuestions(QUIZ_POOL_TIER_1, 5, historySet);
  const t2 = sampleTierQuestions(QUIZ_POOL_TIER_2, 5, historySet);
  const t3 = sampleTierQuestions(QUIZ_POOL_TIER_3, 5, historySet);
  const t4 = sampleTierQuestions(QUIZ_POOL_TIER_4, 5, historySet);

  return [...t1, ...t2, ...t3, ...t4];
}

/**
 * Draw 5 fresh unseen questions for a specific checkpoint tier when retrying
 */
export function refreshTierQuestions(
  tier: 1 | 2 | 3 | 4,
  historySet: Set<number> = new Set()
): ActiveQuizQuestion[] {
  const pool = tier === 1 ? QUIZ_POOL_TIER_1
    : tier === 2 ? QUIZ_POOL_TIER_2
    : tier === 3 ? QUIZ_POOL_TIER_3
    : QUIZ_POOL_TIER_4;

  return sampleTierQuestions(pool, 5, historySet);
}

/**
 * Calculate checkpoint index for retry (Tier 1=0, Tier 2=5, Tier 3=10, Tier 4=15)
 */
export function getCheckpointQuestionIndex(currentIndex: number): number {
  if (currentIndex >= 15) return 15; // Q16 (Tier 4)
  if (currentIndex >= 10) return 10; // Q11 (Tier 3)
  if (currentIndex >= 5) return 5;   // Q6 (Tier 2)
  return 0;                          // Q1 (Tier 1)
}

/**
 * Get tier number from question index (0-based)
 */
export function getTierFromIndex(index: number): 1 | 2 | 3 | 4 {
  if (index >= 15) return 4;
  if (index >= 10) return 3;
  if (index >= 5) return 2;
  return 1;
}

